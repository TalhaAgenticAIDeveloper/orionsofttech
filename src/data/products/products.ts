export function getProductBySlug(slug: string): Product | undefined {
  return products.find((product) => product.slug === slug);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return products.filter((product) => product.categorySlug === categorySlug);
}

export function searchProducts(query: string): Product[] {
  const cleanQuery = query.toLowerCase().trim();
  if (!cleanQuery) return products;

  return products.filter((product) => {
    return (
      product.name.toLowerCase().includes(cleanQuery) ||
      (product.brand && product.brand.toLowerCase().includes(cleanQuery)) ||
      product.shortDescription.toLowerCase().includes(cleanQuery) ||
      product.categorySlug.toLowerCase().includes(cleanQuery) ||
      product.specifications.some(
        (spec) =>
          spec.label.toLowerCase().includes(cleanQuery) ||
          spec.value.toLowerCase().includes(cleanQuery)
      )
    );
  });
}

export function getRelatedProducts(productId: string): Product[] {
  const currentProduct = products.find((p) => p.id === productId);
  if (!currentProduct) return [];

  if (currentProduct.relatedProductIds && currentProduct.relatedProductIds.length > 0) {
    const related = products.filter((p) =>
      currentProduct.relatedProductIds?.includes(p.id)
    );
    if (related.length > 0) return related;
  }

  // Fallback to same category
  return products
    .filter((p) => p.categoryId === currentProduct.categoryId && p.id !== currentProduct.id)
    .slice(0, 3);
}

